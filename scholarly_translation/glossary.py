"""Versioned scholarly terminology glossary.

Pure data: proposals are supplied locally (never generated by a model in
product), and every approval/rejection/revision requires an explicit human
assertion. Source bindings are immutable once proposed; history is a flat,
append-only list of rule versions (no recursive nesting).
"""
from __future__ import annotations
import copy

from .segmentation import validate_structure
from .source_reading import fingerprint, integer, nonempty, sha, strings, text_hash
from .store import deterministic_id

SCHEMA_VERSION = 1
STAGE = "glossary@1"

_RULE_FIELDS = {
    "rule_id", "version", "prior_version", "source_language", "source_term", "target_term",
    "loaded", "status", "scope", "source_binding", "source_context", "review",
}
_BINDING_FIELDS = {
    "document_id", "page_id", "reading_id", "reading_version", "reading_text_hash",
    "unit_id", "unit_version", "unit_text_hash", "source_char_start", "source_char_end",
}


class GlossaryError(ValueError):
    """Invalid glossary contract input; messages contain no supplied source text."""


def _require(condition, message):
    if not condition:
        raise GlossaryError(message)


def new_store():
    return {"schema_version": SCHEMA_VERSION, "stage": STAGE, "revision": 0, "rules": []}


def _validate_scope(scope):
    _require(isinstance(scope, dict) and set(scope) == {"document_ids", "unit_ids"}, "invalid glossary scope shape")
    document_ids, unit_ids = scope["document_ids"], scope["unit_ids"]
    _require(strings(document_ids) and strings(unit_ids)
             and len(set(document_ids)) == len(document_ids) and len(set(unit_ids)) == len(unit_ids),
             "invalid glossary scope entries")


def _validate_rule_row(row):
    _require(isinstance(row, dict) and set(row) == _RULE_FIELDS, "invalid glossary rule shape")
    _require(nonempty(row["rule_id"]) and integer(row["version"])
             and (row["prior_version"] is None
                  or (integer(row["prior_version"]) and row["prior_version"] < row["version"])),
             "invalid glossary rule identity/version")
    _require(nonempty(row["source_language"]) and nonempty(row["source_term"])
             and isinstance(row["target_term"], str) and row["target_term"].strip() != "",
             "invalid glossary rule language/terms")
    _require(type(row["loaded"]) is bool, "invalid glossary rule loaded flag")
    _require(row["status"] in ("proposed", "approved", "rejected"), "invalid glossary rule status")
    _validate_scope(row["scope"])

    binding = row["source_binding"]
    _require(isinstance(binding, dict) and set(binding) == _BINDING_FIELDS, "invalid glossary rule source binding")
    _require(nonempty(binding["document_id"]) and nonempty(binding["page_id"]) and nonempty(binding["reading_id"])
              and integer(binding["reading_version"]) and sha(binding["reading_text_hash"])
              and nonempty(binding["unit_id"]) and integer(binding["unit_version"])
              and sha(binding["unit_text_hash"]) and integer(binding["source_char_start"], 0)
              and integer(binding["source_char_end"]) and binding["source_char_start"] < binding["source_char_end"],
              "invalid glossary rule source binding fields")
    _require(row["rule_id"] == deterministic_id(
        "glossary-rule", binding["document_id"], binding["unit_id"],
        str(binding["source_char_start"]), str(binding["source_char_end"]),
        row["source_language"], row["source_term"]), "glossary rule identity mismatch")
    context = row["source_context"]
    _require(isinstance(context, dict) and set(context) ==
             {"text", "source_char_start", "source_char_end", "source_uri", "pdf_hash"},
             "invalid glossary source context")
    _require(isinstance(context["text"], str) and nonempty(context["source_uri"]) and sha(context["pdf_hash"])
             and integer(context["source_char_start"], 0) and integer(context["source_char_end"])
             and context["source_char_end"] - context["source_char_start"] == len(context["text"])
             and context["source_char_start"] <= binding["source_char_start"] < binding["source_char_end"]
                 <= context["source_char_end"] and binding["unit_text_hash"] == text_hash(context["text"]),
             "glossary context/span/hash mismatch")
    start = binding["source_char_start"] - context["source_char_start"]
    end = binding["source_char_end"] - context["source_char_start"]
    _require(row["source_term"] == context["text"][start:end], "glossary source term differs from context")
    _require(binding["unit_id"] == deterministic_id("unit", binding["document_id"], binding["page_id"],
             binding["reading_id"], str(binding["reading_version"]), str(context["source_char_start"]),
             str(context["source_char_end"])), "glossary unit identity mismatch")

    if row["status"] == "proposed":
        _require(row["review"] is None, "proposed glossary rule cannot carry a review decision")
    else:
        review = row["review"]
        _require(isinstance(review, dict) and set(review) == {"actor", "actor_kind", "reason", "status", "expected_rule_fingerprint"}
                  and nonempty(review["actor"]) and review["actor_kind"] == "human" and nonempty(review["reason"])
                  and review["status"] == row["status"] and sha(review["expected_rule_fingerprint"]),
                  "invalid glossary rule review decision")


def validate_glossary(data):
    _require(isinstance(data, dict) and set(data) == {"schema_version", "stage", "revision", "rules"},
              "invalid glossary shape")
    _require(isinstance(data["rules"], list), "glossary rules must be a list")
    _require(type(data["schema_version"]) is int and data["schema_version"] == SCHEMA_VERSION and data["stage"] == STAGE
              and integer(data["revision"], 0) and data["revision"] == len(data["rules"]),
              "invalid glossary identity/stage")

    by_rule = {}
    for row in data["rules"]:
        _validate_rule_row(row)
        by_rule.setdefault(row["rule_id"], []).append(row)

    for rows in by_rule.values():
        ordered = rows
        _require([r["version"] for r in ordered] == list(range(1, len(ordered) + 1)),
                  "glossary rule version sequence invalid")
        _require(ordered[0]["prior_version"] is None and ordered[0]["status"] == "proposed",
                 "initial glossary rule must be a proposal without prior version")
        for prev, cur in zip(ordered, ordered[1:]):
            _require(cur["prior_version"] == prev["version"], "glossary rule version chain broken")
            _require(cur["review"] is not None and cur["review"]["expected_rule_fingerprint"] == fingerprint(prev),
                     "glossary review does not bind the previous proposal/version")
            for key in ("source_language", "source_term", "source_binding", "source_context", "loaded"):
                _require(cur[key] == prev[key], "glossary rule immutable field changed")


def propose_rule(store, structure, unit_id, source_language, source_char_start, source_char_end,
                  target_term, scope=None, loaded=False):
    validate_glossary(store)
    validate_structure(structure)
    _require(nonempty(source_language), "invalid source language")
    _require(isinstance(target_term, str) and target_term.strip() != "", "invalid proposed target term")
    _require(type(loaded) is bool, "invalid loaded flag")

    unit = next((u for u in structure["units"] if u["unit_id"] == unit_id), None)
    _require(unit is not None, "unknown unit for glossary proposal")
    _require(source_language == unit["language"], "proposal source language differs from source")
    reading = next(r for r in structure["readings"] if r["reading_id"] == unit["reading_id"])

    _require(integer(source_char_start, 0) and integer(source_char_end)
              and unit["source_char_start"] <= source_char_start < source_char_end <= unit["source_char_end"],
              "glossary term span must fall within the proposing unit's source span")
    source_term = reading["text"][source_char_start:source_char_end]
    _require(nonempty(source_term), "glossary term span must be nonempty text")

    scope = {"document_ids": [], "unit_ids": []} if scope is None else scope
    _validate_scope(scope)
    scope = {"document_ids": list(scope["document_ids"]), "unit_ids": list(scope["unit_ids"])}

    binding = {
        "document_id": unit["document_id"], "page_id": unit["page_id"],
        "reading_id": unit["reading_id"], "reading_version": unit["reading_version"],
        "reading_text_hash": unit["reading_text_hash"], "unit_id": unit["unit_id"],
        "unit_version": unit["unit_version"], "unit_text_hash": text_hash(unit["text"]),
        "source_char_start": source_char_start, "source_char_end": source_char_end,
    }
    rule_id = deterministic_id("glossary-rule", binding["document_id"], binding["unit_id"],
                               str(source_char_start), str(source_char_end), source_language, source_term)
    _require(not any(r["rule_id"] == rule_id for r in store["rules"]),
              "glossary rule already proposed for this exact span")

    row = {
        "rule_id": rule_id, "version": 1, "prior_version": None,
        "source_language": source_language, "source_term": source_term, "target_term": target_term,
        "loaded": loaded, "status": "proposed", "scope": scope, "source_binding": binding, "review": None,
        "source_context": {"text": unit["text"], "source_char_start": unit["source_char_start"],
                           "source_char_end": unit["source_char_end"], "source_uri": structure["source_uri"],
                           "pdf_hash": structure["pdf_hash"]},
    }
    new_store = {"schema_version": SCHEMA_VERSION, "stage": STAGE,
                 "revision": store["revision"] + 1, "rules": store["rules"] + [row]}
    validate_glossary(new_store)
    return copy.deepcopy(new_store)


def review_rule(store, rule_id, expected_version, expected_rule_fingerprint, actor, actor_kind, reason, status,
                target_term=None, scope=None):
    validate_glossary(store)
    _require(status in ("approved", "rejected"), "invalid glossary review status")
    _require(actor_kind == "human", "glossary rules can only be approved or rejected by a human")
    _require(nonempty(actor) and nonempty(reason), "invalid glossary review actor/reason")

    rows = [r for r in store["rules"] if r["rule_id"] == rule_id]
    _require(rows, "unknown glossary rule_id")
    current = max(rows, key=lambda r: r["version"])
    _require(integer(expected_version) and current["version"] == expected_version, "stale glossary rule version")
    _require(fingerprint(current) == expected_rule_fingerprint, "stale glossary rule fingerprint")

    new_target = current["target_term"] if target_term is None else target_term
    _require(isinstance(new_target, str) and new_target.strip() != "", "invalid revised target term")
    if scope is None:
        new_scope = current["scope"]
    else:
        _validate_scope(scope)
        new_scope = {"document_ids": list(scope["document_ids"]), "unit_ids": list(scope["unit_ids"])}

    row = dict(current)
    row["version"] = current["version"] + 1
    row["prior_version"] = current["version"]
    row["target_term"] = new_target
    row["scope"] = new_scope
    row["status"] = status
    row["review"] = {"actor": actor, "actor_kind": "human", "reason": reason, "status": status,
                     "expected_rule_fingerprint": expected_rule_fingerprint}

    new_store = {"schema_version": SCHEMA_VERSION, "stage": STAGE,
                 "revision": store["revision"] + 1, "rules": store["rules"] + [row]}
    validate_glossary(new_store)
    return copy.deepcopy(new_store)


def resolve_applicable(store, structure, unit_id):
    """Return applicable approved/proposed rules for a real, validated unit.

    Only rules whose language/scope/term literally apply feed the fingerprint;
    conflicting approved targets for the same term are excluded and reported,
    never silently chosen.
    """
    validate_glossary(store)
    validate_structure(structure)
    unit = next((u for u in structure["units"] if u["unit_id"] == unit_id), None)
    _require(unit is not None, "unknown unit for glossary resolution")

    latest = {}
    for row in store["rules"]:
        current = latest.get(row["rule_id"])
        if current is None or row["version"] > current["version"]:
            latest[row["rule_id"]] = row

    def applies(row):
        if row["source_language"] != unit["language"] or row["source_term"] not in unit["text"]:
            return False
        scope = row["scope"]
        if scope["document_ids"] and unit["document_id"] not in scope["document_ids"]:
            return False
        if scope["unit_ids"] and unit["unit_id"] not in scope["unit_ids"]:
            return False
        return True

    approved = [r for r in latest.values() if r["status"] == "approved" and applies(r)]
    proposed = [r for r in latest.values() if r["status"] == "proposed" and applies(r)]

    by_term = {}
    for r in approved:
        by_term.setdefault(r["source_term"], []).append(r)

    warnings, effective = [], []
    for term, rules in by_term.items():
        targets = {r["target_term"] for r in rules}
        if len(targets) > 1:
            warnings.append(f"conflicting_approved_target:{term}")
        else:
            effective.extend(rules)

    effective = sorted(effective, key=lambda r: r["rule_id"])
    policy_fingerprint = effective_fingerprint(effective)

    return copy.deepcopy({
        "schema_version": SCHEMA_VERSION, "stage": "terminology-resolution@1", "unit_id": unit_id,
        "approved_rules": effective, "proposed_rules": sorted(proposed, key=lambda r: r["rule_id"]),
        "status": "needs_human" if warnings else "ready", "unit_hash": fingerprint(unit),
        "warnings": warnings, "policy_fingerprint": policy_fingerprint,
    })


def effective_fingerprint(rules):
    """Only applied terminology meaning/scope; review metadata is not a dependency."""
    return fingerprint([{k: r[k] for k in
                        ("rule_id", "source_language", "source_term", "target_term", "scope", "loaded")}
                        for r in sorted(rules, key=lambda r:r["rule_id"])])


def validate_resolution(resolution, unit):
    fields = {"schema_version", "stage", "unit_id", "unit_hash", "approved_rules",
              "proposed_rules", "status", "warnings", "policy_fingerprint"}
    _require(isinstance(resolution, dict) and set(resolution) == fields
             and type(resolution["schema_version"]) is int and resolution["schema_version"] == 1
             and resolution["stage"] == "terminology-resolution@1"
             and resolution["unit_id"] == unit["unit_id"] and resolution["unit_hash"] == fingerprint(unit),
             "invalid terminology resolution source binding")
    _require(isinstance(resolution["approved_rules"], list) and isinstance(resolution["proposed_rules"], list)
             and strings(resolution["warnings"]), "invalid terminology resolution collections")
    seen, targets = set(), {}
    for expected, collection in (("approved", resolution["approved_rules"]), ("proposed", resolution["proposed_rules"])):
        for row in collection:
            _validate_rule_row(row)
            _require(row["status"] == expected and row["rule_id"] not in seen
                     and row["source_language"] == unit["language"] and row["source_term"] in unit["text"],
                     "invalid applicable rule")
            scope = row["scope"]
            _require((not scope["document_ids"] or unit["document_id"] in scope["document_ids"])
                     and (not scope["unit_ids"] or unit["unit_id"] in scope["unit_ids"]), "rule scope mismatch")
            seen.add(row["rule_id"])
            if expected == "approved":
                prior = targets.setdefault(row["source_term"], row["target_term"])
                _require(prior == row["target_term"], "conflicting effective terminology")
    _require(resolution["status"] == ("needs_human" if resolution["warnings"] else "ready")
             and resolution["policy_fingerprint"] == effective_fingerprint(resolution["approved_rules"]),
             "invalid terminology policy fingerprint/status")
